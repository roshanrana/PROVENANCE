"""Regenerate every figure in docs/figures/ from bench/results/measurements.json.

`CLAUDE.md`: *figures are regenerated by script, never hand-edited.* So this
script is the only thing that writes them, it reads one file, and that file is
the same one `tests/test_published_numbers.py` pins the prose to. A figure and a
sentence cannot disagree without a test failing.

Plain SVG, emitted by hand. Not because a plotting library would be hard, but
because the output is then diffable text with no dependency, and a reviewer can
check that a bar is the length the number says it is. A chart in a repository
about verifiable claims should itself be verifiable.

Two files per figure, `-light.svg` and `-dark.svg`, referenced from a `<picture>`
element. The dark steps are chosen for the dark surface rather than being an
inverted copy of the light ones.

    uv run python scripts/make_figures.py
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "bench" / "results" / "measurements.json"
OUT = ROOT / "docs" / "figures"


@dataclass(frozen=True)
class Theme:
    """Colour roles. The dark column is stepped for the dark surface (see the
    reference palette), not derived by inverting the light one."""

    name: str
    surface: str
    ink: str
    ink_soft: str
    grid: str
    series1: str  # blue
    series2: str  # orange
    good: str
    bad: str

    @property
    def is_dark(self) -> bool:
        return self.name == "dark"


LIGHT = Theme(
    "light", "#fcfcfb", "#0b0b0b", "#52514e", "#dedddb", "#2a78d6", "#eb6834", "#1baf7a", "#e34948"
)
DARK = Theme(
    "dark", "#1a1a19", "#ffffff", "#c3c2b7", "#3a3a38", "#3987e5", "#d95926", "#199e70", "#e66767"
)

FONT = (
    "ui-sans-serif,-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,"
    "'Helvetica Neue',Arial,sans-serif"
)
MONO = "ui-monospace,SFMono-Regular,Menlo,Consolas,monospace"


def esc(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


class Svg:
    """A tiny SVG writer. Enough for bars, rules and text; nothing more."""

    def __init__(self, width: int, height: int, theme: Theme, title: str) -> None:
        self.w, self.h, self.t = width, height, theme
        self.parts: list[str] = []
        self.title = title

    def rect(self, x: float, y: float, w: float, h: float, fill: str, rx: float = 0) -> None:
        if w <= 0 or h <= 0:
            return
        self.parts.append(
            f'<rect x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" '
            f'rx="{rx:.1f}" fill="{fill}"/>'
        )

    def line(
        self,
        x1: float,
        y1: float,
        x2: float,
        y2: float,
        stroke: str,
        width: float = 1,
        dash: str | None = None,
    ) -> None:
        d = f' stroke-dasharray="{dash}"' if dash else ""
        self.parts.append(
            f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" '
            f'stroke="{stroke}" stroke-width="{width}"{d}/>'
        )

    def text(
        self,
        x: float,
        y: float,
        s: str,
        *,
        size: float = 12,
        fill: str | None = None,
        anchor: str = "start",
        weight: str = "400",
        mono: bool = False,
    ) -> None:
        family = MONO if mono else FONT
        self.parts.append(
            f'<text x="{x:.1f}" y="{y:.1f}" font-family="{family}" font-size="{size}" '
            f'font-weight="{weight}" fill="{fill or self.t.ink}" '
            f'text-anchor="{anchor}">{esc(s)}</text>'
        )

    def render(self) -> str:
        body = "\n  ".join(self.parts)
        return (
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.w}" height="{self.h}" '
            f'viewBox="0 0 {self.w} {self.h}" role="img" aria-label="{esc(self.title)}">\n'
            f"  <title>{esc(self.title)}</title>\n"
            f'  <rect width="{self.w}" height="{self.h}" fill="{self.t.surface}"/>\n'
            f"  {body}\n</svg>\n"
        )


def write(name: str, build: Any) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for theme in (LIGHT, DARK):
        (OUT / f"{name}-{theme.name}.svg").write_text(build(theme), encoding="utf-8")
    print(f"  {name}-light.svg / {name}-dark.svg")


