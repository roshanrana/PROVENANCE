def fig_s02_power(data: dict[str, Any]) -> Any:
    th = data["thresholds"]
    runs = data["s02"]["runs"]

    def build(t: Theme) -> str:
        w, h = 720, 336
        s = Svg(w, h, t, "S-02: the interval narrowing as n grew")
        s.text(
            24,
            30,
            "Why the sample size was fixed before the run that counted",
            size=15,
            weight="600",
        )
        s.text(
            24,
            50,
            "S-02 latency channel, AUC with its 95% bootstrap interval",
            size=12,
            fill=t.ink_soft,
        )

        rows = [
            {
                "label": f"run #{r['run']}  (n={r['n']})",
                "auc": r["auc"],
                "ci": r["ci"],
                "clears": r["clears_bar"],
                "annot": f"AUC {r['auc']:.4f}  p={r['p']:.4g}",
            }
            for r in runs
        ]
        bottom = _interval_panel(
            s, t, rows, x0=250, x1=520, top=112, row_h=44, label_x=236, thresholds=th
        )
        s.text(
            24,
            bottom + 40,
            "Runs #8 and #11 both sat above chance with an interval straddling it. "
            "That is not evidence of no effect;",
            size=11,
            fill=t.ink_soft,
        )
        s.text(
            24,
            bottom + 56,
            "it is what n=62 looks like when it cannot resolve an effect of that size. "
            "n=402 was fixed in the workflow",
            size=11,
            fill=t.ink_soft,
        )
        s.text(
            24,
            bottom + 72,
            "BEFORE the run that got recorded, so the answer could not be reached by "
            "stopping when it looked convenient.",
            size=11,
            fill=t.ink_soft,
        )
        return s.render()

    return build


def main() -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    print(f"reading {DATA.relative_to(ROOT)}")
    write("divergence", fig_divergence(data))
    write("cost-decomposition", fig_decomposition(data))
    write("frb03-verdict", fig_frb03(data))
    write("s02-power", fig_s02_power(data))
    print(f"wrote {OUT.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
