def _interval_panel(
    s: Svg,
    t: Theme,
    rows: list[dict[str, Any]],
    *,
    x0: float,
    x1: float,
    top: float,
    row_h: float,
    label_x: float,
    thresholds: dict[str, float],
    lo: float = 0.35,
    hi: float = 1.05,
) -> float:
    """Shared AUC-with-interval panel. One axis, chance and the bar marked."""

    def px(v: float) -> float:
        return x0 + (v - lo) / (hi - lo) * (x1 - x0)

    bottom = top + len(rows) * row_h
    for v, label, dash in (
        (thresholds["chance"], "chance 0.5", "3 3"),
        (thresholds["auc_success"], "pre-registered bar 0.75", "3 3"),
    ):
        s.line(px(v), top - 12, px(v), bottom + 4, t.grid, 1, dash=dash)
        s.text(px(v), top - 20, label, size=10, anchor="middle", fill=t.ink_soft)

    for i, r in enumerate(rows):
        y = top + i * row_h + row_h / 2
        clears = bool(r.get("clears"))
        colour = t.bad if clears else t.good
        s.text(label_x, y + 4, r["label"], size=12, anchor="end")
        ci_lo, ci_hi = r["ci"]
        # A degenerate interval still has to be visible, so it gets a minimum width.
        a, b = px(ci_lo), px(ci_hi)
        if b - a < 3:
            a, b = a - 1.5, b + 1.5
        s.rect(a, y - 4, b - a, 8, colour, rx=4)
        s.line(px(r["auc"]), y - 11, px(r["auc"]), y + 11, colour, 2)
        s.text(x1 + 14, y + 4, r["annot"], size=11, mono=True, fill=t.ink_soft)
    return bottom


def fig_frb03(data: dict[str, Any]) -> Any:
    th = data["thresholds"]
    profiles = {p["profile"]: p for p in data["frb03"]["profiles"]}

    def build(t: Theme) -> str:
        w, h = 720, 334
        s = Svg(w, h, t, "FR-B-03: the routing-index leak and its mitigation")
        s.text(
            24, 30, "The cross-tenant leak, and the mitigation closing it", size=15, weight="600"
        )
        s.text(
            24,
            50,
            "same schedule, same pre-registered rule — 40 trials per profile, n=80",
            size=12,
            fill=t.ink_soft,
        )

        rows = [
            {
                "label": "default (stock llm-d)",
                "auc": profiles["default"]["auc"],
                "ci": profiles["default"]["ci"],
                "clears": True,
                "annot": "AUC 1.0000  p=9.999e-05",
            },
            {
                "label": "hardened (tenant salt)",
                "auc": profiles["hardened"]["auc"],
                "ci": profiles["hardened"]["ci"],
                "clears": False,
                "annot": "AUC 0.5000  at chance",
            },
        ]
        bottom = _interval_panel(
            s, t, rows, x0=250, x1=520, top=112, row_h=52, label_x=236, thresholds=th
        )
        for i, (name, colour) in enumerate((("attack succeeds", t.bad), ("at chance", t.good))):
            lx = 250 + i * 130
            s.rect(lx, 62, 10, 10, colour, rx=2)
            s.text(lx + 16, 71, name, size=11, fill=t.ink_soft)
        s.text(
            24,
            bottom + 44,
            "Positive class: tenant A probing a prefix tenant B planted. Negative: a "
            "prefix nobody planted.",
            size=11,
            fill=t.ink_soft,
        )
        s.text(
            24,
            bottom + 60,
            "A CONFIRMATION oracle — the probe sends the victim's prompt verbatim, so a "
            "perfect match is by construction.",
            size=11,
            fill=t.ink_soft,
        )
        s.text(
            24,
            bottom + 76,
            "It shows an attacker who can guess a prefix gets it confirmed. It does not "
            "show unknown content can be recovered.",
            size=11,
            fill=t.ink_soft,
        )
        s.text(
            24,
            bottom + 92,
            "Both intervals are degenerate — every observation is identical — so they "
            "render as a tick. That is zero variance, not precision.",
            size=11,
            fill=t.ink_soft,
        )
        return s.render()

    return build


