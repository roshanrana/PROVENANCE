def fig_decomposition(data: dict[str, Any]) -> Any:
    cells = {c["id"]: c for c in data["sglang_2x2"]["cells"]}
    ratios = {r["name"]: r for r in data["sglang_2x2"]["ratios"]}

    def build(t: Theme) -> str:
        w, h = 720, 372
        s = Svg(w, h, t, "Caching x determinism, decomposed, on SGLang")
        s.text(
            24,
            30,
            "The cost of determinism, separated from the cost of losing the cache",
            size=15,
            weight="600",
        )
        s.text(
            24,
            50,
            "SGLang on an H100, mean output tokens/second, 128 trials per cell",
            size=12,
            fill=t.ink_soft,
        )

        base_y, top_y = 256, 92
        scale = (base_y - top_y) / 400.0
        groups = [("determinism off", "B", "A"), ("determinism on", "D", "C")]
        gx = [150, 430]
        bw, bgap = 76, 12

        for gi, (gname, off_id, on_id) in enumerate(groups):
            for bi, (cid, colour) in enumerate(((off_id, t.series1), (on_id, t.series2))):
                cell = cells[cid]
                x = gx[gi] + bi * (bw + bgap)
                bh = cell["tokens_per_s"] * scale
                s.rect(x, base_y - bh, bw, bh, colour, rx=4)
                s.text(
                    x + bw / 2,
                    base_y - bh - 10,
                    f"{cell['tokens_per_s']:.1f}",
                    size=12,
                    weight="600",
                    anchor="middle",
                    mono=True,
                )
                s.text(
                    x + bw / 2,
                    base_y + 18,
                    f"cell {cid}",
                    size=11,
                    anchor="middle",
                    fill=t.ink_soft,
                )
            s.text(gx[gi] + bw + bgap / 2, base_y + 38, gname, size=12, anchor="middle")

        s.line(120, base_y, w - 40, base_y, t.grid, 1)

        # Legend: two series, so a legend is always present. Placed in the
        # header band rather than over the plot, where it collided with the
        # tallest bar's direct label.
        for i, (name, colour) in enumerate((("cache off", t.series1), ("cache on", t.series2))):
            lx = w - 230 + i * 108
            s.rect(lx, 42, 10, 10, colour, rx=2)
            s.text(lx + 16, 51, name, size=11, fill=t.ink_soft)

        y = 308
        s.text(24, y, "D / B", size=12, weight="600", mono=True)
        s.text(
            90,
            y,
            f"{ratios['D / B']['value']:.3f}x",
            size=12,
            weight="600",
            mono=True,
            fill=t.series2,
        )
        s.text(160, y, "determinism alone costs 18.0%, cache held off on both sides", size=12)
        s.text(24, y + 20, "C / A", size=12, mono=True, fill=t.ink_soft)
        s.text(90, y + 20, f"{ratios['C / A']['value']:.3f}x", size=12, mono=True, fill=t.ink_soft)
        s.text(
            160,
            y + 20,
            "both together — the only comparison a vLLM-shaped experiment can make",
            size=12,
            fill=t.ink_soft,
        )
        s.text(
            24,
            y + 42,
            "The confounded number UNDERSTATES the cost here: the cache is a small "
            "penalty on this workload, not a benefit.",
            size=11,
            fill=t.ink_soft,
        )
        return s.render()

    return build


