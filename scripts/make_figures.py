def fig_divergence(data: dict[str, Any]) -> Any:
    cells = data["divergence"]["cells"]

    def build(t: Theme) -> str:
        w, h = 720, 320
        s = Svg(w, h, t, "Distinct logprob vectors in 128 identical requests")
        left, top, bar_h, gap = 250, 74, 26, 18
        span = w - left - 90
        s.text(
            24, 30, "Batched inference is not reproducible at temperature 0", size=15, weight="600"
        )
        s.text(
            24,
            50,
            "distinct logprob vectors in 128 identical requests — lower is better",
            size=12,
            fill=t.ink_soft,
        )

        for i, c in enumerate(cells):
            y = top + i * (bar_h + gap)
            label = f"{c['engine']}, determinism {'on' if c['determinism'] else 'off'}"
            s.text(
                left - 14,
                y + bar_h * 0.72,
                label,
                size=12,
                anchor="end",
                fill=t.ink if c["determinism"] else t.ink_soft,
            )
            width = span * c["distinct"] / 34
            colour = t.series1 if c["engine"] == "vLLM" else t.series2
            s.rect(left, y, max(width, 3), bar_h, colour, rx=4)
            s.text(
                left + max(width, 3) + 10,
                y + bar_h * 0.72,
                f"{c['distinct']} of 128",
                size=12,
                weight="600",
                mono=True,
            )

        base = top + len(cells) * (bar_h + gap) + 4
        s.line(left, base, left + span, base, t.grid, 1)
        s.text(
            24,
            base + 30,
            "The two engines ran under their own defaults and schedulers.",
            size=11,
            fill=t.ink_soft,
        )
        s.text(
            24,
            base + 46,
            "Read as two measurements, not as a controlled comparison.",
            size=11,
            fill=t.ink_soft,
        )
        return s.render()

    return build


